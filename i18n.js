let LANG = (() => {
  try {
    if (localStorage.lang) return localStorage.lang;
  } catch {}
  return /^it/i.test(navigator.language || 'it') ? 'it' : 'en';
})();

function t(s, vars) {
  let out = LANG === 'en' && EN[s] != null ? EN[s] : s;
  if (vars) for (const k in vars) out = out.split('{' + k + '}').join(vars[k]);
  return out;
}

// Traduce i testi scritti nell'HTML (ricorda l'originale italiano)
function applyI18n(root = document.body) {
  document.documentElement.lang = LANG;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) => (n.parentNode && /^(SCRIPT|STYLE|CANVAS)$/.test(n.parentNode.nodeName) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const n of nodes) {
    if (n.__it == null) {
      const raw = n.nodeValue.trim();
      if (!raw || !(raw in EN)) continue;
      n.__it = raw;
    }
    const lead = n.nodeValue.match(/^\s*/)[0], trail = n.nodeValue.match(/\s*$/)[0];
    n.nodeValue = lead + t(n.__it) + trail;
  }
  for (const attr of ['placeholder', 'aria-label', 'alt', 'title']) {
    root.querySelectorAll(`[${attr}]`).forEach((el) => {
      const key = 'it' + attr.replace(/-./, (m) => m[1].toUpperCase());
      if (el.dataset[key] == null) {
        const v = el.getAttribute(attr);
        if (!(v in EN)) return;
        el.dataset[key] = v;
      }
      el.setAttribute(attr, t(el.dataset[key]));
    });
  }
}
function setLang(l) {
  LANG = l;
  try { localStorage.lang = l; } catch {}
  applyI18n();
}
